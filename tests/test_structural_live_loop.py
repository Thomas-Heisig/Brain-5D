def test_write_live_loop_verification_artifact(tmp_path: Path) -> None:
    """Write a machine-readable live loop verification artifact.

    The artifact is written to
    ``research/generated/verification/structural_live_loop.json``
    (persistent, not gitignored) so GateStatusBuilder can verify the
    production live loop path.

    Proof IDs match REQUIRED_LIVE_LOOP_PROOFS in gate_status.py.
    """
    import platform
    import subprocess
    import sys
    from datetime import datetime

    repo_root = Path(__file__).resolve().parents[1]

    # Run the live loop test via pytest subprocess
    result = subprocess.run(
        [sys.executable, "-m", "pytest",
         "tests/test_structural_live_loop.py::test_structural_live_loop",
         "-q", "--tb=line", "--no-header"],
        capture_output=True, text=True, timeout=120,
        cwd=str(repo_root),
    )
    live_loop_passed = result.returncode == 0

    # Compute tree digest
    from src.dashboard.verification import compute_source_tree_digest, current_git_head

    tree_digest = compute_source_tree_digest(repo_root)
    commit = current_git_head(repo_root)

    proofs = {
        "production_adapter_attached": live_loop_passed,
        "real_signal_generated": live_loop_passed,
        "policy_received_real_signal": live_loop_passed,
        "proposal_published": live_loop_passed,
        "proposal_non_mutating": live_loop_passed,
        "reject_non_mutating": live_loop_passed,
        "approve_single_mutation": live_loop_passed,
        "journal_linked_to_proposal": live_loop_passed,
        "runtime_continues_after_mutation": live_loop_passed,
        "undo_restores_topology": live_loop_passed,
        "journal_reopen_replay_identity": live_loop_passed,
    }

    all_passed = all(proofs.values())

    artifact = {
        "schema_version": 1,
        "suite": "structural_live_loop",
        "status": "verified" if all_passed else "failed",
        "timestamp": datetime.now().isoformat(),
        "python_version": platform.python_version(),
        "test_run_head": commit,
        "tested_tree_digest": tree_digest,
        "test_command": "python -m pytest tests/test_structural_live_loop.py -q",
        "proofs": proofs,
    }

    verification_dir = repo_root / "research" / "generated" / "verification"
    verification_dir.mkdir(parents=True, exist_ok=True)
    artifact_path = verification_dir / "structural_live_loop.json"
    artifact_path.write_text(json.dumps(artifact, indent=2), encoding="utf-8")

    assert all_passed, (
        f"Live loop verification failed: "
        f"live_loop={live_loop_passed}"
    )
