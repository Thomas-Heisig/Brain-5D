@pytest.fixture
def live_config() -> dict[str, Any]:
    """Load the dedicated live config.

    Uses the raw YAML loader to get all sections (the validated loader
    strips homeostasis, self_organization, and storage sections).
    """
    import yaml
    config_dict: dict[str, Any] = load_config(str(_LIVE_CONFIG))
    # Merge raw sections that the validated loader strips
    with open(str(_LIVE_CONFIG), "r", encoding="utf-8") as f:
        raw = yaml.safe_load(f) or {}
    for key in ("homeostasis", "self_organization", "storage", "eligibility", "max_neurons"):
        if key in raw:
            config_dict[key] = raw[key]
    return config_dict


def test_structural_live_loop(tmp_path: Path, live_config: dict[str, Any]) -> None:
    """Complete Alpha.5 structural live loop E2E test.

    This test proves the entire production path:
    real Network -> real ticks -> real HomeostasisSignal
    -> config-authoritative Policy -> real Proposal -> Coordinator
    -> no mutation before approval -> OperatorBridge -> manual approval
    -> exactly one mutation -> journal -> undo -> replay
    """
    # Clear error buffer before starting
    get_error_buffer().clear()

    # ====================================================================
    # A. Build network and runtime with structural live config
    # ====================================================================
    network = _build_network_from_config(live_config)

    # Create and attach homeostasis
    homeostasis = HomeostasisEngine(network, live_config)
    assert homeostasis.enabled, "Homeostasis must be enabled in live config"
    homeostasis.attach()

    # ====================================================================
    # B. Confirm all components are active
    # ====================================================================
    so_cfg = live_config.get("self_organization", {})
    _allow_neurogenesis = bool(so_cfg.get("neurogenesis_enabled", True))
    _allow_neuron_pruning = bool(so_cfg.get("pruning_enabled", False))
    _allow_synapse_sprouting = bool(so_cfg.get("sprouting_enabled", False))
    _allow_synapse_pruning = bool(so_cfg.get("synapse_pruning_enabled", False))

    journal_path = tmp_path / "structural_live.journal"
    composed = compose_structural_subsystem(
        network,
        journal_path,
        coordinator_enabled=True,
        coordinator_dry_run=False,
        max_changes_per_tick=1,
        allow_neurogenesis=_allow_neurogenesis,
        allow_neuron_pruning=_allow_neuron_pruning,
        allow_synapse_sprouting=_allow_synapse_sprouting,
        allow_synapse_pruning=_allow_synapse_pruning,
        create_controller=True,
        create_bridge=True,
    )
    plasticity = composed["plasticity"]
    coordinator = composed["coordinator"]
    journal = composed["journal"]
    bridge = composed["bridge"]
    controller = composed["controller"]  # Use the controller from composition

    assert coordinator is not None
    assert plasticity is not None
    assert journal is not None
    assert bridge is not None
    assert controller is not None

    # Attach the RuntimeAdapter with config-authoritative settings
    policy_config = SelfOrganizationPolicyConfig.from_config(live_config)
    adapter = SelfOrganizationRuntimeAdapter(
        homeostasis_engine=homeostasis,
        coordinator=coordinator,
        interval_ticks=int(so_cfg.get("interval_ticks", 50)),
        policy_config=policy_config,
    )
    controller.add_hook(adapter)

    # ====================================================================
    # C. Advance real ticks
    # ====================================================================
    controller.run_ticks(300)

    # ====================================================================
    # D. Check that a proposal was generated from real measurements
    # ====================================================================
    report = coordinator.latest()
    if report is None or len(report.proposals) == 0:
        controller.run_ticks(300)
        report = coordinator.latest()

    if report is None or len(report.proposals) == 0:
        controller.run_ticks(400)
        report = coordinator.latest()

    assert report is not None, (
        "No PolicyReport produced after 1000 ticks. "
        "Check that homeostasis is generating a signal and the adapter is attached."
    )
    assert len(report.proposals) > 0, (
        f"No proposals generated after 1000 ticks. "
        f"Neurogenesis pressure={report.neurogenesis_pressure:.3f}, "
        f"enabled={policy_config.neurogenesis_enabled}"
    )

    proposal = report.proposals[0]
    assert proposal.kind.value == "neurogenesis", (
        f"Expected neurogenesis proposal, got {proposal.kind}"
    )
    assert proposal.reason, "Proposal must have a reason string"
    assert proposal.confidence > 0.0, "Proposal must have positive confidence"

    # Verify the adapter has no errors
    error_buffer = get_error_buffer()
    assert error_buffer.count == 0, (
        f"RuntimeAdapter produced {error_buffer.count} errors: "
        f"{[e.message for e in error_buffer.events]}"
    )

    # ====================================================================
    # E. Capture topology digest before proposal
    # ====================================================================
    digest_before = _structural_digest(network)

    # ====================================================================
    # F. Verify proposal exists in coordinator
    # ====================================================================
    proposal_id = proposal.proposal_id
    found = coordinator.find(proposal_id)
    assert found is not None, f"Proposal {proposal_id} not found in coordinator"

    # ====================================================================
    # G. Verify topology is unchanged before approval
    # ====================================================================
    digest_still_before = _structural_digest(network)
    assert digest_before == digest_still_before, (
        "Topology changed before approval -- unexpected mutation"
    )

    # ====================================================================
    # H. Verify proposal observable through OperatorBridge
    # ====================================================================
    bridge_proposals = bridge.structural_proposals()
    bridge_ids = [p["proposal_id"] for p in bridge_proposals]
    assert proposal_id in bridge_ids, (
        f"Proposal {proposal_id} not found in OperatorBridge proposals: {bridge_ids}"
    )

    # ====================================================================
    # I. Reject one proposal
    # ====================================================================
    reject_result = bridge.reject_structural(proposal_id)
    assert reject_result.ok, f"Rejection failed: {reject_result.message}"

    digest_after_reject = _structural_digest(network)
    assert digest_after_reject == digest_before, "Topology changed after rejection"

    history_after_reject = journal.history(100)
    assert len(history_after_reject) == 0, (
        f"Journal has records after rejection (expected 0): {len(history_after_reject)}"
    )

    # ====================================================================
    # J. Generate another real proposal (continue running)
    # ====================================================================
    controller.run_ticks(200)

    report2 = coordinator.latest()
    assert report2 is not None, "No report after additional ticks"
    assert len(report2.proposals) > 0, "No proposals after additional ticks"

    # Must approve from the CURRENT latest report
    proposal2 = report2.proposals[0]
    proposal2_id = proposal2.proposal_id
    assert proposal2_id != proposal_id, "Same proposal ID -- expected a new proposal"

    # ====================================================================
    # K. Approve exactly one proposal via the bridge
    # ====================================================================
    neuron_count_before_approval = len(network.neurons)
    approve_result = bridge.apply_proposal(
        proposal2_id, approved=True
    )
    assert approve_result["ok"], f"Approval failed: {approve_result.get('error', '')}"

    # ====================================================================
    # L. Verify exactly one mutation
    # ====================================================================
    digest_after_approval = _structural_digest(network)
    assert digest_after_approval != digest_before, "Topology unchanged after approval"

    neuron_count_after = len(network.neurons)
    assert neuron_count_after == neuron_count_before_approval + 1, (
        f"Expected exactly 1 new neuron, got {neuron_count_after - neuron_count_before_approval}"
    )

    history = journal.history(100)
    assert len(history) == 1, f"Expected exactly 1 journal record, got {len(history)}"
    record = history[0]
    assert record.kind == StructuralChangeKind.NEURON_ADD, (
        f"Expected NEURON_ADD, got {record.kind}"
    )
    assert record.proposal_id == proposal2_id, (
        f"Journal proposal_id {record.proposal_id} != {proposal2_id}"
    )
    assert record.tick > 0, "Journal record tick must be > 0"
    assert record.neuron_id is not None, "Journal record must have neuron_id"

    # ====================================================================
    # M. Continue runtime after mutation -- network remains operable
    # ====================================================================
    controller.run_ticks(100)

    assert len(network.neurons) > 0, "Network has no neurons after mutation + ticks"
    # Use RuntimeController — the sole simulation-clock owner
    controller.run_ticks(1)

    # ====================================================================
    # N. Undo restores topology
    # ====================================================================
    undo_result = plasticity.undo_last_change(tick=controller.telemetry.tick + 1)
    assert undo_result is True, "Undo failed"

    digest_after_undo = _structural_digest(network)
    assert digest_after_undo == digest_before, (
        "Topology after undo does not match pre-mutation state"
    )

    history_after_undo = journal.history(100)
    assert len(history_after_undo) >= 2, (
        f"Expected at least 2 journal records after undo, got {len(history_after_undo)}"
    )
    last_record = history_after_undo[-1]
    assert last_record.kind == StructuralChangeKind.NEURON_REMOVE, (
        f"Expected NEURON_REMOVE for undo, got {last_record.kind}"
    )

    # ====================================================================
    # O. Re-open journal from disk and replay into fresh network
    # ====================================================================
    net2 = _build_network_from_config(live_config)
    journal2 = StructuralJournal(journal_path)

    composed2 = compose_structural_subsystem(
        net2,
        journal_path,
        coordinator_enabled=False,
        coordinator_dry_run=True,
    )
    plasticity2 = composed2["plasticity"]

    records = journal2.history(100)
    for rec in records:
        if rec.kind in (StructuralChangeKind.NEURON_ADD, StructuralChangeKind.SYNAPSE_ADD):
            plasticity2.apply_structural_record(rec)

    digest_after_replay = _structural_digest(net2)
    assert digest_after_replay == digest_after_approval, (
        "Replayed network topology does not match post-mutation state"
    )

    # ====================================================================
    # Verify no RuntimeAdapter errors occurred throughout
    # ====================================================================
    assert error_buffer.count == 0, (
        f"RuntimeAdapter produced {error_buffer.count} errors during live loop: "
        f"{[e.message for e in error_buffer.events]}"
    )


