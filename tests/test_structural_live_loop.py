"""Alpha.5 Structural Live Loop E2E test.

This test proves the production path for the first real closed structural
regulation loop. It uses the production composition/runtime adapter path
and the dedicated live config (configs/poc_structural_live.yaml).

Required sequence:

A. Start real network/runtime with structural live config.
B. Confirm:
   - Homeostasis active
   - Self-Organization active
   - Coordinator active
   - PlasticityEngine active
   - StructuralJournal active
   - RuntimeAdapter attached
C. Advance real ticks through RuntimeController.
D. Obtain a proposal generated by:
   real Network -> real HomeostasisSignal -> production RuntimeAdapter
   -> SelfOrganizationPolicy -> Coordinator
E. Capture canonical topology digest before proposal.
F. Verify proposal exists.
G. Verify topology digest is unchanged before approval.
H. Verify proposal is observable through OperatorBridge.
I. Reject one proposal:
   - rejection succeeds
   - topology unchanged
   - no mutation StructuralChangeRecord produced for rejection
J. Generate another real proposal.
K. Approve exactly one proposal.
L. Verify:
   - exactly one expected structural mutation
   - topology digest changes
   - exactly one committed StructuralChangeRecord for that mutation
   - proposal_id linkage matches
   - tick/provenance fields are present where supported
M. Continue runtime for additional ticks after mutation.
   The network must remain operable.
N. Undo:
   - inverse-record path used
   - topology digest returns exactly to pre-mutation structural digest
O. Re-open StructuralJournal from disk in a fresh instance and replay
   into a fresh equivalent base network. Verify topology identity for
   the applicable post-mutation state.

IMPORTANT:
Structural digest remains structural only:
- neuron id
- coordinate
- synapse source
- synapse target
- weight
- delay

Do not include v/u/energy in the structural digest.
Full dynamic state equality belongs to Restore Determinism later.
"""

