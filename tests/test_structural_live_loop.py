# =========================================================================
# Helper: build network from the live config
# =========================================================================


def _build_network_from_config(config_dict: dict[str, Any]) -> NeuralNetwork:
    """Build a NeuralNetwork from a config dict, same as src.main."""
    config = Brain5DConfig.from_dict(config_dict)
    rng = random.Random(int(config_dict.get("seed", 42)))
    network = NeuralNetwork(config, rng)
    dims = config.dimensions

    total_positions = 1
    for d in dims:
        total_positions *= d

    initial_neurons = int(config_dict.get("initial_neurons", 100))
    chosen = random.Random(42).sample(range(total_positions), initial_neurons)

    for idx in sorted(chosen):
        network.add_neuron(linear_to_5d(idx, dims))

    conn_per_neuron = config.network.initial_connections_per_neuron
    radius = config.network.neighbour_radius
    network.initialize_random_connections(conn_per_neuron, radius)
    return network


